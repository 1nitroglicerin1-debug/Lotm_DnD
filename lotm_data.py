def tier_data(path: str, sequence: int) -> dict:
    """Данные тира последовательности для пути."""
    return PATHWAYS.get(path, {}).get("tiers", {}).get(sequence, {})


def abilities_for_build(path: str, choices: dict[str, str]) -> list[dict]:
    """Собирает полный список умений билда.

    choices: {"9": "a"|"b", "8": ...} — выбранная ветка на каждой открытой последовательности.
    """
    out: list[dict] = []
    for seq in SEQUENCES:
        td = tier_data(path, seq)
        if not td:
            continue
        choice = choices.get(str(seq))
        if choice is None:
            continue
        core = td.get("core")
        if core:
            out.append(_ability(core, seq, "core", path))
        branch = td.get("choice_a" if choice == "a" else "choice_b")
        if branch:
            out.append(_ability(branch, seq, choice, path))
    return out


def _ability(data: tuple, seq: int, kind: str, path: str) -> dict:
    name, act, save, dice, desc = data
    tier = TIER_OF_SEQUENCE.get(seq, 0)
    return {
        "name": name,
        "action": act,
        "action_label": action_label(act),
        "save": save,
        "dice": dice,
        "desc": desc,
        "sequence": seq,
        "tier": tier,
        "kind": kind,          # core | a | b
        "path": path,
        "slot_rank": SLOT_RANK_OF_TIER.get(tier, 0),  # 0 = бесплатно
        "cost": 0 if act == "passive" else SLOT_RANK_OF_TIER.get(tier, 0),
    }


def hp_factor(sequence: int) -> int:
    """Суммарный множитель HP по текущей последовательности (Посл.9 = 2 ... Посл.4 = 12)."""
    return HP_FACTOR_BY_SEQUENCE.get(int(sequence or 9), 2)


def spell_slots_for(sequence: int, feats: list[str] | None = None) -> dict[int, int]:
    """Ячейки духовности по текущей последовательности (с учётом черт)."""
    slots = dict(SLOTS_BY_SEQUENCE.get(sequence, {}))
    if feats and "deep_sea" in feats:
        for rank in (1, 2):
            if rank in slots:
                slots[rank] += 1
    if feats and "sefirot_aura" in feats:
        for rank in (3, 4):
            if rank in slots:
                slots[rank] += 1
    return slots


def max_hp_for(path: str, sequence: int, con_mod: int, feats: list[str] | None = None) -> int:
    """Максимум HP = множитель последовательности × K, где K = 4 + кость хитов + мод. ТЕЛ."""
    seq = int(sequence or 9)
    bone = PATHWAYS.get(path, {}).get("bone", 8)
    if isinstance(bone, str):
        bone = int(str(bone).lstrip("d"))
    k = 4 + bone + con_mod
    hp = hp_factor(seq) * k
    if feats and "inhuman_vitality" in feats:
        hp += 3 * OPEN_TIERS.get(seq, 1)
    return max(hp, 1)


def prof_bonus(sequence: int) -> int:
    return PROF_BY_SEQUENCE.get(sequence, 2)


def count_skills(sequence: int) -> int:
    """Всего скиллов пути у игрока: 2 (ядро + выбор) за каждый открытый тир."""
    return 2 * OPEN_TIERS.get(int(sequence or 9), 1)

