def pathway_stat_bonus(path: str) -> dict[str, int]:
    """Каноничный бонус характеристик от принятия зелья Пути:
    +2 к основной профильной характеристике, +1 ко второй профильной и +1 к ТЕЛ.
    """
    raw = PATHWAYS.get(path, {}).get("stat", "int")
    parts = [s.strip() for s in raw.split("/") if s.strip()]
    if not parts:
        parts = ["int"]
    bonuses: dict[str, int] = {}
    bonuses[parts[0]] = 2
    if len(parts) > 1:
        bonuses[parts[1]] = bonuses.get(parts[1], 0) + 1
    else:
        bonuses["wis" if parts[0] != "wis" else "int"] = 1
    bonuses["con"] = bonuses.get("con", 0) + 1
    return bonuses
