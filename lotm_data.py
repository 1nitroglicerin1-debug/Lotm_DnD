def sibling_paths(path: str) -> list[str]:
    """Смежные пути внутри группы (для смены пути на 4-й последовательности)."""
    group = GROUP_OF_PATH.get(path)
    if not group:
        return []
    return [p for p in PATHWAY_GROUPS[group] if p != path]


